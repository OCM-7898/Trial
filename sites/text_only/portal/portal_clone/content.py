from .seed import content

_LOOKUP_HINTS = ("status", "verify", "verification", "track", "search",
                 "lookup", "-check")


def panel_items(lang="en"):
    items = {}
    for slug, c in content(lang).items():
        rows = []
        for item_slug, meta in c["panel"].items():
            rows.append({
                "slug": item_slug,
                "title": meta["title"],
                "summary": meta["summary"],
                "lookup": any(h in item_slug for h in _LOOKUP_HINTS),
            })
        items[slug] = rows
    return items


