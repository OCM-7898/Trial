import pathlib
import random
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

SEED = 45_2026
GLOBAL_EMERGENCY = "+251 11 517 8888"

HOURS = [
    ("Monday to Friday 08:30-17:30, Saturday 09:00-13:00, closed Sunday",
     "ከሰኞ እስከ ዓርብ 08:30-17:30፣ ቅዳሜ 09:00-13:00፣ እሁድ ዝግ"),
    ("Monday to Friday 09:00-17:00, closed weekends",
     "ከሰኞ እስከ ዓርብ 09:00-17:00፣ ቅዳሜና እሁድ ዝግ"),
    ("Sunday to Thursday 08:00-16:00, closed Friday and Saturday",
     "ከእሁድ እስከ ሐሙስ 08:00-16:00፣ ዓርብና ቅዳሜ ዝግ"),
    ("Daily 07:00-20:00", "በየቀኑ 07:00-20:00"),
]


def main() -> None:
    rng = random.Random(SEED)
    airports = yaml.safe_load(
        (ROOT / "spec/seed_data/airports.yaml").read_text("utf-8"))["airports"]

    seen: dict[str, dict] = {}
    for airport in airports:
        seen.setdefault(airport["country_code"], airport)

    countries = sorted(seen.items())[:45]
    assert len(countries) == 45, f"need 45 country offices, have {len(countries)}"

    rows = []
    for index, (code, airport) in enumerate(countries, start=1):
        local = f"+{200 + index} {rng.randint(10, 99)} {rng.randint(100, 999)} {rng.randint(1000, 9999)}"
        hours = HOURS[index % len(HOURS)]
        has_desk = index % 3 != 0
        rows.append({
            "id": index,
            "country_code": code,
            "country_en": airport["country_en"], "country_am": airport["country_am"],
            "city_en": airport["city_en"], "city_am": airport["city_am"],
            "phone": local,
            "emergency_phone": GLOBAL_EMERGENCY,
            "email": f"{code.lower()}.office@selamairways.example",
            "hours_en": hours[0], "hours_am": hours[1],
            "address_en": f"{airport['city_en']} City Office, {100 + index} Airport Road, "
                          f"{airport['city_en']}, {airport['country_en']}",
            "address_am": f"የ{airport['city_am']} ከተማ ቢሮ፣ {100 + index} የአየር ማረፊያ መንገድ፣ "
                          f"{airport['city_am']}፣ {airport['country_am']}",
            "has_ticket_desk": has_desk,
        })

    out = ROOT / "spec/seed_data/contact_offices.yaml"
    out.write_text("# Generated by tools/make_contacts.py -- edit there, not here.\n"
                   + yaml.safe_dump({"contact_offices": rows}, sort_keys=False,
                                    allow_unicode=True), "utf-8")
    desks = sum(1 for r in rows if r["has_ticket_desk"])
    print(f"wrote {out.relative_to(ROOT)} -- {len(rows)} offices")
    print(f"  with a ticket desk: {desks}; without: {len(rows) - desks}")
    print(f"  all carry a 24-hour line ({GLOBAL_EMERGENCY}) distinct from local hours")
    for row in rows[:4]:
        print(f"  {row['country_code']} {row['country_en']:<16} {row['phone']}")


if __name__ == "__main__":
    main()
