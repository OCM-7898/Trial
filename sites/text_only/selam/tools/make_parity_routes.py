import pathlib
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.routes_map import SLUGS

SAMPLES = {
    "checkin_id": "1", "fare_class": "EF", "iata": "ADD", "city": "NBO",
    "offer_id": "1",
    "lounge_id": "2",
    "flight_no": "SM222", "origin": "ADD",
    "destination": "NBO", "country": "ET", "category": "baggage",
}

QUERY = {
    "results": "?origin=ADD&destination=NBO&depart=2026-04-12&return=2026-04-19&adults=1",
    "flight_status": "?flight_no=SM222&date=2026-04-12",
    "schedules": "?origin=ADD&destination=NBO",
    "award_search": "?origin=ADD&destination=NBO&date=2026-04-12",
    "miles_account": "",
    "lounge_eligibility": "?airport=ADD&cabin=economy&tier=gold",
    "lounges": "?airport=ADD",
    "bag_allowance": "?origin=ADD&destination=LHR&cabin=economy&pax_type=adult",
    "seats": "?segment_id=1",
    "change": "?segment_id=1",
    "upgrade": "?segment_id=1",
    "bag_add": "?segment_id=1",
}

SKIP = {"reset", "reset_status", "boarding_pass", "manage_itinerary_pdf",
        "help_topic"}


def main() -> None:
    with sqlite3.connect(ROOT / "data" / "seed.db") as conn:
        pnr = conn.execute("select pnr from bookings order by id limit 1").fetchone()[0]
    SAMPLES["pnr"] = pnr

    lines = [
        "# Generated by tools/make_parity_routes.py -- edit there, not here.",
        "# Crawl list for verify_parity.py (SPEC.md 13). One URL per line.",
        f"# Path parameters use seeded values; PNR {pnr} is the first seeded booking.",
        "",
    ]
    for name, template in sorted(SLUGS.items()):
        if name in SKIP:
            continue
        url = template
        for parameter, value in SAMPLES.items():
            url = url.replace(f"<{parameter}>", value)
        if "<" in url:
            raise SystemExit(f"no sample value for a parameter in {name}: {template}")
        lines.append(url + QUERY.get(name, ""))

    with sqlite3.connect(ROOT / "data" / "seed.db") as conn:
        dedicated = {"allergies", "special-baggage"}
        for (slug,) in conn.execute("select slug from content_pages order by slug"):
            if slug not in dedicated:
                lines.append(SLUGS["help_topic"].replace("<slug>", slug))

    out = ROOT / "spec" / "parity_routes.txt"
    out.write_text("\n".join(lines) + "\n", "utf-8")
    print(f"wrote {out.relative_to(ROOT)} -- {len(lines) - 4} URLs")


if __name__ == "__main__":
    main()
