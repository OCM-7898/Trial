import math
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

HUB = "ADD"

SECONDARY = [
    ("NBO", "MBA"), ("NBO", "EBB"), ("DAR", "ZNZ"), ("JNB", "DUR"),
    ("JNB", "GBE"), ("LOS", "ACC"), ("DXB", "BOM"), ("JNB", "WDH"),
]

def weekly_days(distance_km: float, region: str, is_hub_route: bool) -> str:
    if not is_hub_route:
        return "1...5.."
    if distance_km < 700:
        return "12.45.7"
    if region == "africa":
        return "1..4..7" if distance_km < 2500 else "1...5.."
    if region in ("middle_east", "europe"):
        return "1..4..7" if distance_km < 5000 else "1...5.."
    return "1...5.."


def haversine(lat1, lon1, lat2, lon2) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = math.radians(lat2 - lat1), math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return round(2 * r * math.asin(math.sqrt(a)), 0)


def block_time(distance_km: float) -> int:
    return int(round((distance_km / 800.0 * 60 + 35) / 5.0) * 5)


def main() -> None:
    airports = {a["iata"]: a for a in
                yaml.safe_load((ROOT / "spec/seed_data/airports.yaml").read_text("utf-8"))["airports"]}

    pairs = [(HUB, iata) for iata in sorted(airports) if iata != HUB]
    pairs += [p for p in SECONDARY]

    rows, route_id, flight_no = [], 1, 100
    for origin, destination in pairs:
        o, d = airports[origin], airports[destination]
        dist = haversine(o["latitude"], o["longitude"], d["latitude"], d["longitude"])
        is_hub = HUB in (origin, destination)
        region = d["region"] if origin == HUB else o["region"]
        days = weekly_days(dist, region, is_hub)
        bt = block_time(dist)
        for a, b, no in ((origin, destination, flight_no), (destination, origin, flight_no + 1)):
            rows.append({
                "id": route_id, "origin": a, "destination": b,
                "distance_km": int(dist), "block_time_min": bt,
                "operating_days": days, "flight_no": f"SM{no}",
            })
            route_id += 1
        flight_no += 2

    departures_per_day = sum(7 - r["operating_days"].count(".") for r in rows) / 7.0
    assert flight_no <= 999, "flight numbers must stay within SM100-SM999 (SPEC.md 3)"

    out = ROOT / "spec/seed_data/routes.yaml"
    out.write_text(
        "# Generated by tools/make_routes.py -- edit there, not here.\n"
        "# See that file for why this is 164 routes and not the 140 in SPEC.md 12.\n"
        + yaml.safe_dump({"routes": rows}, sort_keys=False, allow_unicode=True),
        "utf-8",
    )
    print(f"wrote {out}")
    print(f"  routes             {len(rows)} directional ({len(pairs)} city pairs)")
    print(f"  airports served    {len({r['origin'] for r in rows})} of {len(airports)}")
    print(f"  departures/day     {departures_per_day:.1f}  (target ~60)")
    print(f"  flight numbers     SM100-SM{flight_no - 1}")


if __name__ == "__main__":
    main()
