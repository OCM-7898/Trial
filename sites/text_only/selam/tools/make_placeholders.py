from __future__ import annotations

import hashlib
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "static" / "img" / "cards"

PALETTE = [
    ("#0B5D51", "#12796A", "#E8A33D"),
    ("#12796A", "#0B5D51", "#F0C070"),
    ("#0E4C6B", "#12796A", "#E8A33D"),
    ("#8A5A2B", "#B07B3E", "#F0C070"),
    ("#3D5A45", "#587A62", "#E8A33D"),
]

SLOTS = [
    "baggage", "checkin", "miles", "lounge", "stopover", "status",
    "destinations", "offers", "onboard", "partners", "cargo", "help",
]

WIDTH, HEIGHT = 640, 400


def _seed(name: str) -> int:
    return int.from_bytes(hashlib.sha256(name.encode()).digest()[:8], "big")


def render(name: str) -> str:
    seed = _seed(name)
    deep, mid, accent = PALETTE[seed % len(PALETTE)]

    horizon = HEIGHT * (0.55 + 0.2 * ((seed >> 8) % 5) / 4)
    disc_x = WIDTH * (0.18 + 0.55 * ((seed >> 16) % 7) / 6)
    disc_y = horizon * (0.35 + 0.3 * ((seed >> 24) % 4) / 3)
    disc_r = 34 + ((seed >> 32) % 5) * 9
    stroke_count = 3 + ((seed >> 40) % 3)

    strokes = []
    for index in range(stroke_count):
        y = horizon + 26 + index * 30
        if y > HEIGHT - 14:
            break
        inset = 40 + ((seed >> (44 + index * 3)) % 6) * 34
        strokes.append(
            f'<rect x="{inset}" y="{y:.0f}" width="{WIDTH - inset * 2}" '
            f'height="8" rx="4" fill="{accent}" opacity="0.55"/>')

    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" '
        f'width="{WIDTH}" height="{HEIGHT}" role="presentation">'
        f'<rect width="{WIDTH}" height="{HEIGHT}" fill="{deep}"/>'
        f'<path d="M0 {horizon:.0f} L{WIDTH} {horizon - 40:.0f} L{WIDTH} {HEIGHT} '
        f'L0 {HEIGHT} Z" fill="{mid}"/>'
        f'<circle cx="{disc_x:.0f}" cy="{disc_y:.0f}" r="{disc_r}" fill="{accent}"/>'
        + "".join(strokes) +
        '</svg>\n'
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    for name in SLOTS:
        target = OUT / f"{name}.svg"
        target.write_text(render(name), "utf-8")
        written.append(target)

    bodies = {p.read_text("utf-8") for p in written}
    assert len(bodies) == len(written), (
        f"{len(written) - len(bodies)} placeholder(s) are byte-identical to "
        f"another; vary the palette or the geometry")
    for path in written:
        text = path.read_text("utf-8")
        assert "<text" not in text and "font" not in text, (
            f"{path.name} contains text; a caption inside the file would be the "
            f"same Latin string in both builds")

    manifest = ROOT / "spec" / "card_placeholders.md"
    manifest.write_text(
        "# Card placeholders\n\n"
        "Generated by `tools/make_placeholders.py`. Original geometric SVG in "
        "the Selam Airways palette; nothing here is derived from any real "
        "airline's imagery, and no photography was fetched for this build.\n\n"
        "They carry no text: a caption inside the file would render as Latin "
        "script on the Amharic pages. Captions are alt text on the page, "
        "translated through `t()`.\n\n"
        + "".join(f"- `{p.name}` -- {p.stat().st_size} bytes\n"
                 for p in written), "utf-8")

    print(f"wrote {len(written)} placeholders to {OUT.relative_to(ROOT)}")
    print(f"  manifest     {manifest.relative_to(ROOT)}")
    print(f"  distinct     {len(bodies)}")
    print(f"  largest      {max(p.stat().st_size for p in written)} bytes")


if __name__ == "__main__":
    main()
