def main() -> None:
    rows = [{"id": i, "category": c, "name_en": n[0], "name_am": n[1],
             "description_en": d[0], "description_am": d[1],
             "min_layover_h": lo, "max_layover_h": hi,
             "cabin_required": cabin, "price_usd": price}
            for i, (c, n, d, lo, hi, cabin, price) in enumerate(PACKAGES, 1)]

    thresholds = sorted({r["min_layover_h"] for r in rows})
    assert len(thresholds) >= 3, (
        f"only {len(thresholds)} distinct layover thresholds ({thresholds}); the "
        f"service list would be the same for every eligible itinerary and 'list "
        f"the available services' would not depend on reading it")
    assert any(r["cabin_required"] for r in rows), \
        "no option is cabin-restricted, so cabin never changes the answer"

    out = ROOT / "spec/seed_data/stopover.yaml"
    out.write_text("# Generated by tools/make_stopover.py -- edit there, not here.\n"
                   + yaml.safe_dump({"stopover_packages": rows},
                                    sort_keys=False, allow_unicode=True), "utf-8")
    print(f"wrote {out.relative_to(ROOT)} -- {len(rows)} packages")
    for threshold in thresholds:
        n = sum(1 for r in rows if r["min_layover_h"] <= threshold)
        print(f"  a {threshold}h layover unlocks {n} of {len(rows)} options")


if __name__ == "__main__":
    main()
