REVIEW_ROUTES = tuple(k for k, v in SLUGS.items() if v.endswith("/review"))


def path(key: str, **params: object) -> str:
    p = SLUGS[key]
    for name, value in params.items():
        p = p.replace(f"<{name}>", str(value))
    if "<" in p:
        raise KeyError(f"unfilled parameter in route {key!r}: {p}")
    return p
